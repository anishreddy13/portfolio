"""
copilot_models.py — Data Models for Enterprise AI Trading Copilot

Defines CopilotMessage, CopilotSuggestion, CopilotAction, CopilotExecutionPlan,
CopilotConversation, and CopilotStatistics dataclasses with JSON serialization.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional


class MessageSender(str, Enum):
    USER = "USER"
    ASSISTANT = "ASSISTANT"
    SYSTEM = "SYSTEM"


class CopilotIntent(str, Enum):
    EXPLAIN_SIGNAL = "EXPLAIN_SIGNAL"
    EXPLAIN_PORTFOLIO = "EXPLAIN_PORTFOLIO"
    EXPLAIN_RISK = "EXPLAIN_RISK"
    RECOMMEND_TRADE = "RECOMMEND_TRADE"
    RECOMMEND_REBALANCE = "RECOMMEND_REBALANCE"
    RECOMMEND_HEDGE = "RECOMMEND_HEDGE"
    GENERAL_QUERY = "GENERAL_QUERY"


@dataclass
class CopilotAction:
    """Proposed action recommended by EnterpriseCopilot."""
    action_id: str
    action_type: str
    target_symbol: str
    parameters: Dict[str, Any] = field(default_factory=dict)
    status: str = "PROPOSED"  # PROPOSED, ACCEPTED, REJECTED

    def to_dict(self) -> Dict[str, Any]:
        return {
            "action_id": self.action_id,
            "action_type": self.action_type,
            "target_symbol": self.target_symbol,
            "parameters": self.parameters,
            "status": self.status,
        }


@dataclass
class CopilotSuggestion:
    """Actionable copilot suggestion item."""
    suggestion_id: str
    title: str
    description: str
    category: str = "TRADE"  # TRADE, HEDGE, REBALANCE, RISK_ALERT
    confidence: float = 0.90

    def to_dict(self) -> Dict[str, Any]:
        return {
            "suggestion_id": self.suggestion_id,
            "title": self.title,
            "description": self.description,
            "category": self.category,
            "confidence": round(self.confidence, 2),
        }


@dataclass
class CopilotExecutionPlan:
    """Multi-step execution plan generated by EnterpriseCopilot."""
    plan_id: str
    title: str
    steps: List[Dict[str, Any]] = field(default_factory=list)
    estimated_impact: str = ""
    compliance_status: str = "PASSED"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "plan_id": self.plan_id,
            "title": self.title,
            "steps": self.steps,
            "estimated_impact": self.estimated_impact,
            "compliance_status": self.compliance_status,
        }


@dataclass
class CopilotMessage:
    """Chat message in a copilot conversation."""
    msg_id: str
    sender: str
    content: str
    timestamp: str
    actions: List[CopilotAction] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "msg_id": self.msg_id,
            "sender": self.sender,
            "content": self.content,
            "timestamp": self.timestamp,
            "actions": [a.to_dict() for a in self.actions],
        }


@dataclass
class CopilotConversation:
    """Conversation thread with history."""
    conv_id: str
    title: str
    created_at: str
    messages: List[CopilotMessage] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "conv_id": self.conv_id,
            "title": self.title,
            "created_at": self.created_at,
            "messages": [m.to_dict() for m in self.messages],
        }


@dataclass
class CopilotStatistics:
    """Operational statistics for EnterpriseCopilot."""
    total_conversations: int = 0
    total_queries_answered: int = 0
    total_plans_generated: int = 0
    total_recommendations_made: int = 0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "total_conversations": self.total_conversations,
            "total_queries_answered": self.total_queries_answered,
            "total_plans_generated": self.total_plans_generated,
            "total_recommendations_made": self.total_recommendations_made,
        }
