"""
signal_models.py — Data Models for Enterprise Signal Engine

Defines SignalDirection, SignalSource, SignalStrength, TradingSignal,
SignalScore, SignalDecision, and SignalStatistics dataclasses with JSON serialization.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional


class SignalDirection(str, Enum):
    BUY = "BUY"
    SELL = "SELL"
    HOLD = "HOLD"
    FLAT = "FLAT"


class SignalSource(str, Enum):
    EMA_CROSSOVER = "EMA_CROSSOVER"
    RSI_MEAN_REVERSION = "RSI_MEAN_REVERSION"
    MACD_MOMENTUM = "MACD_MOMENTUM"
    BOLLINGER_BREAKOUT = "BOLLINGER_BREAKOUT"
    COMPOSITE = "COMPOSITE"


@dataclass
class SignalStrength:
    """Signal strength and conviction rating."""
    value: float = 0.85
    confidence: float = 0.90
    level: str = "STRONG_CONVICTION"

    def to_dict(self) -> Dict[str, Any]:
        """Convert SignalStrength to clean dictionary."""
        return {
            "value": round(self.value, 2),
            "confidence": round(self.confidence, 2),
            "level": self.level,
        }


@dataclass
class TradingSignal:
    """Standardized trading signal envelope generated by quantitative strategies."""
    signal_id: str
    symbol: str
    direction: str = "BUY"
    source: str = "COMPOSITE"
    strength: SignalStrength = field(default_factory=SignalStrength)
    suggested_price: float = 182.50
    stop_loss: float = 178.85
    take_profit: float = 189.80
    time_to_live_sec: int = 60
    timestamp: str = ""
    is_expired: bool = False

    def to_dict(self) -> Dict[str, Any]:
        return {
            "signal_id": self.signal_id,
            "symbol": self.symbol,
            "direction": self.direction,
            "source": self.source,
            "strength": self.strength.to_dict(),
            "suggested_price": round(self.suggested_price, 2),
            "stop_loss": round(self.stop_loss, 2),
            "take_profit": round(self.take_profit, 2),
            "time_to_live_sec": self.time_to_live_sec,
            "timestamp": self.timestamp,
            "is_expired": self.is_expired,
        }


@dataclass
class SignalScore:
    """Calculated composite score metrics for ranking signals."""
    score: float = 88.5
    concordance_ratio: float = 1.0
    volatility_penalty: float = 0.05
    overall_rank: int = 1

    def to_dict(self) -> Dict[str, Any]:
        return {
            "score": round(self.score, 1),
            "concordance_ratio": round(self.concordance_ratio, 2),
            "volatility_penalty": round(self.volatility_penalty, 2),
            "overall_rank": self.overall_rank,
        }


@dataclass
class SignalDecision:
    """Resolution decision returned after scoring & conflict resolution."""
    is_approved: bool
    winning_signal: Optional[TradingSignal] = None
    conflict_resolved: bool = False
    rejection_reason: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "is_approved": self.is_approved,
            "winning_signal": self.winning_signal.to_dict() if self.winning_signal else None,
            "conflict_resolved": self.conflict_resolved,
            "rejection_reason": self.rejection_reason,
        }


@dataclass
class SignalStatistics:
    """Operational metrics tracking the SignalEngine."""
    total_signals_received: int = 0
    active_signals_count: int = 0
    conflicts_resolved: int = 0
    expired_signals_cleared: int = 0
    approved_signals_count: int = 0

    def to_dict(self) -> Dict[str, Any]:
        return {
            "total_signals_received": self.total_signals_received,
            "active_signals_count": self.active_signals_count,
            "conflicts_resolved": self.conflicts_resolved,
            "expired_signals_cleared": self.expired_signals_cleared,
            "approved_signals_count": self.approved_signals_count,
        }
