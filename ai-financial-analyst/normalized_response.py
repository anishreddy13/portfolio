"""
normalized_response.py — Universal Enterprise Data Wrapper

Defines the single canonical wrapper object NormalizedResponse[T] that encapsulates
every provider data payload before downstream engine consumption.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, Generic, List, TypeVar

from market_types import ProviderType

T = TypeVar("T")


@dataclass
class NormalizedResponse(Generic[T]):
    """Universal canonical wrapper for all normalized market data entities.

    Attributes:
        value: The underlying normalized data payload (e.g. Quote, HistoricalSeries, CompanyFundamentals).
        provider: ProviderType origin tag (e.g. ProviderType.POLYGON, ProviderType.ALPACA).
        provider_timestamp: ISO timestamp generated by the original provider.
        received_timestamp: ISO timestamp when payload was received by ingestion layer.
        normalized_timestamp: ISO timestamp when normalization transformation occurred.
        confidence: Normalized data confidence score (0.0 to 1.0).
        staleness_ms: Calculated latency / age of payload in milliseconds.
        agreement_status: Multi-provider agreement state ('AGREED', 'DISCREPANCY', 'SINGLE_SOURCE', 'UNKNOWN').
        validation_flags: List of schema and range validation tags.
        quality_flags: List of data quality markers (e.g. 'UNADJUSTED_BARS', 'STALE_QUOTE', 'OUTLIER_REJECTED').
        metadata: Arbitrary provider-specific metadata key-value pairs.
    """
    value: T
    provider: ProviderType = ProviderType.INTERNAL
    provider_timestamp: str = ""
    received_timestamp: str = ""
    normalized_timestamp: str = ""
    confidence: float = 1.0
    staleness_ms: int = 0
    agreement_status: str = "SINGLE_SOURCE"
    validation_flags: List[str] = field(default_factory=list)
    quality_flags: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        """Convert NormalizedResponse wrapper to clean dictionary."""
        val_dict = self.value.to_dict() if hasattr(self.value, "to_dict") else self.value
        return {
            "value": val_dict,
            "provider": self.provider.value if hasattr(self.provider, "value") else str(self.provider),
            "provider_timestamp": self.provider_timestamp,
            "received_timestamp": self.received_timestamp,
            "normalized_timestamp": self.normalized_timestamp,
            "confidence": round(self.confidence, 4),
            "staleness_ms": self.staleness_ms,
            "agreement_status": self.agreement_status,
            "validation_flags": self.validation_flags,
            "quality_flags": self.quality_flags,
            "metadata": self.metadata,
        }
